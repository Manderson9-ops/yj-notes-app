// 결정적 위급 신호 검사(red flag). 질문 글에서 키워드를 찾으면 답 단계를 10(지금 바로 진료·연락)으로 고정한다.
// 앱 화면(즉시 경고)과 서버(저장)가 같은 모듈을 쓴다. AI 없음. 놓침보다 과잉 경고를 택한다.
// 공백을 모두 없앤 글에서 찾는다(「숨 이 안 쉬어져」 같은 띄어쓰기 변형 대응).
// 합성 키워드만. 질문 본문은 어디에도 기록하지 않는다.

const RED_FLAG_PATTERNS: readonly RegExp[] = [
  // 숨·호흡
  /숨(?:을|이)?(?:못|안|쉬기|쉬는|가빠|이차|막|넘어|멈|헐떡)/,
  /호흡(?:곤란|이힘|이가빠|이안|을못)/,
  /헐떡/,
  /숨쉬기힘/,
  /숨을못/,
  // 피부색·의식
  /파랗게|파래(?:져|졌|요|서)|입술이파|얼굴이파|새파/,
  /의식(?:이|을)?(?:없|잃|흐려|흐리|저하)/,
  /깨워도|깨우기힘|안깨|축처져|축늘어|늘어져서(?:안|못)/,
  /반응(?:이|을)?(?:없|안)/,
  // 경련
  /경련|발작|거품(?:을)?물/,
  // 삼킴·중독
  /삼켰|삼킨(?:것|듯|거)|삼켜버|삼킴|삼켜서(?:안|못)/,
  /독(?:을|이)?(?:먹|마셨|마시)|독극물|세제(?:를)?(?:먹|마셨|마시)|약(?:을)?(?:잘못|많이|몰래|한꺼번에|혼자)먹|건전지|자석(?:을)?(?:먹|삼)/,
  // 외상·출혈
  /심하게(?:다쳤|다침|다쳐)|많이다쳤|크게다쳤/,
  /피(?:가|를)?(?:많이|계속|안멈|멈추지)|출혈/,
  /머리(?:를|가)?(?:세게)?(?:부딪|박았|찧|부딪혔)|머리(?:를)?다쳤/,
  // 열·탈수
  /고열|열이(?:40|39|높|펄펄|안내)|40도|39도/,
  /탈수|소변(?:이|을)?(?:안|거의안)|오줌(?:을|이)?(?:안|거의안)|기저귀가(?:안|마른)/,
  // 자해·학대
  /자해|스스로(?:를)?(?:해치|때리|다치게)|죽고싶|죽겠다고/,
  /학대|(?:누가|선생님이|친구가|형이|언니가)때렸|맞고(?:왔|있)|멍이(?:많|계속|곳곳)/,
  // 갑작스런 변화
  /갑자기(?:못|걷지|걸을수|말을?안|말이안|말을못|말을하지|눈이|한쪽)/,
  /갑자기(?:안걸|말을잃)/,
];

export interface RedFlagResult {
  redFlag: boolean;
  /** 걸린 규칙의 번호(디버그·시험용). 원문 조각은 담지 않는다. */
  rules: number[];
}

/** 질문 글에 위급 신호가 있는가. */
export function detectRedFlag(body: string): RedFlagResult {
  const squeezed = body.normalize("NFC").replace(/[\s\u200b]+/g, "");
  const rules: number[] = [];
  RED_FLAG_PATTERNS.forEach((p, i) => {
    if (p.test(squeezed)) rules.push(i);
  });
  return { redFlag: rules.length > 0, rules };
}

export const RED_FLAG_RULE_COUNT = RED_FLAG_PATTERNS.length;
